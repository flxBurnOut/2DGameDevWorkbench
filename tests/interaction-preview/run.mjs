import assert from 'node:assert/strict';
import './import.mjs';
import { worldPoint, localPoint, sampleAt, evaluateInteraction } from '../../features/interaction-preview/model.mjs';

const p={position:{x:30,y:50},origin:{x:10,y:20},scale:2,flip_x:true,depth:0};
assert.deepEqual(worldPoint({x:13,y:17},p),{x:24,y:44});
assert.deepEqual(localPoint({x:24,y:44},p),{x:13,y:17});
const placement={position:{x:0,y:0},origin:{x:0,y:0},scale:1,flip_x:false,depth:0};
const anchor=(frames)=>[{id:'contact',samples:frames.map((point,frame)=>({frame,state:point?'visible':'unknown',point}))}];
const at={x:10,y:20},far={x:40,y:20};
const frames=[0,1].map(index=>({index,raw_index:index+1,sha256:String(index),width:64,height:64}));
const source={fps:2,frames};
