const context={actor:structuredClone(placement),object:structuredClone(placement),actor_anchors:anchor([at,at]),object_states:[obj,{...obj,id:'response',anchors:anchor([at,at,at,at])}],initial_state:'initial',events:[],relations:[{
  id:'r',name:'接触保持',kind:'attached',actor_anchor:'contact',object_anchor:'contact',window:{start:0,end:1},tolerance_px:2,response_state:null,response_window:null}]};
assert.equal(sampleAt(source,context,.3).actor.raw_index,1,'playback mapping preserves excluded reference frame');
assert.equal(sampleAt(source,context,.3).object.frame,1,'object follows its own FPS');
assert.equal(sampleAt(source,context,.999).actor.index,1);
let result=evaluateInteraction(source,context)[0];
assert.equal(result.status,'mismatch','must inspect faster object frames between actor ticks');
