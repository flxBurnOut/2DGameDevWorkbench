context.actor_anchors[0].samples[1]={frame:1,state:'inferred',point:at};
assert.equal(evaluateInteraction(source,context)[0].status,'unknown','inference cannot be promoted to contact evidence');
context.actor_anchors=anchor([at,at]);
context.relations[0].response_state='response';context.relations[0].response_window={start:.2,end:.4};
context.events=[{time:.8,from_state:'initial',to_state:'response'}];
result=evaluateInteraction(source,context)[0];assert.equal(result.status,'mismatch');assert.equal(result.timing.error_seconds,.4);
context.events[0].time=.3;
assert.equal(evaluateInteraction(source,context)[0].status,'matched');
assert.equal(sampleAt(source,context,0).object.state.id,'initial','scrubbing/restarting resets response deterministically');
