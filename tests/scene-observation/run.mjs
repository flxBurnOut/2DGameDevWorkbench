import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import sharp from 'sharp';
import { createProject, createObject } from '../../features/interactable-editor/contract.mjs';
import { createScene, addMaterial, addInstance, replaceMap, sceneWarnings } from '../../features/scene-composer/model.mjs';
import { objectRenderState, instanceRect } from '../../features/scene-composer/render-model.mjs';
import { observeScene } from '../../lib/workbench/scene-observation.mjs';

const root = await mkdtemp(path.join(os.tmpdir(), 'forge-observation-'));
const image = async (width, height, color) => `data:image/png;base64,${(await sharp({ create: { width, height, channels: 4, background: color } }).png().toBuffer()).toString('base64')}`;
try {
  const scene = createScene('观察测试');
  replaceMap(scene, { name: '背景', origin: { x: -10, y: -20 }, offset: { x: 0, y: 0 }, source: 'fixture', warnings: [], collisions: [], layers: [{ id: 'map_overall', name: '背景', source: await image(100, 100, '#0000ff'), width: 100, height: 100, locked: false, hidden: false, included: true }] });
  const project = createProject();
  const object = project.objects[0];
  project.assets.push({ id: 'red', name: 'red.png', mime: 'image/png', source: await image(20, 20, '#ff0000') });
  Object.assign(object.visual, { assetId: 'red', width: 20, height: 20 });
  const material = addMaterial(scene, project, object.definitionId);
  const instance = addInstance(scene, material.id, 10, 10);
  scene.revision = 3;
  const document = { id: scene.id, kind: 'scene', revision: 3, contentHash: 'a'.repeat(64), content: scene };
  const manifest = { workspace: { outputDirectory: 'outputs' } };
  const observed = await observeScene(root, manifest, document);
  assert.equal(observed.complete, true);
  assert.equal(observed.revision, 3);
  assert.deepEqual(observed.viewport.worldToImage, [1, 0, 0, 1, 10, 20]);
  assert.equal(observed.images.length, 2);
  assert.deepEqual(observed.objects[0].rect, instanceRect(instance, material));
  const png = await sharp(Buffer.from(observed.images[0].data, 'base64')).raw().toBuffer({ resolveWithObject: true });
  const pixel = (x, y) => [...png.data.subarray((y * png.info.width + x) * 4, (y * png.info.width + x) * 4 + 4)];
  assert.deepEqual(pixel(15, 20), [255, 0, 0, 255], 'Frontmost instance must cover background.');
  assert.deepEqual(pixel(50, 50), [0, 0, 255, 255]);
  const metadata = JSON.parse(await readFile(path.join(root, path.dirname(observed.images[0].artifactPath), 'observation.json'), 'utf8'));
  assert.equal(metadata.images[0].data, undefined, 'Evidence JSON must not duplicate image base64.');
  const crop = await observeScene(root, manifest, document, { region: { x: 0, y: 0, width: 10, height: 10 }, overlay: false });
  assert.deepEqual(crop.viewport.worldToImage, [1, 0, 0, 1, -0, -0]);
  assert.equal(crop.images.length, 1);
  assert.equal(crop.images[0].width, 10);
  const large = structuredClone(document);
  const noise = randomBytes(1900 * 1500 * 3);
  const largeImage = await sharp(noise, { raw: { width: 1900, height: 1500, channels: 3 } }).png().toBuffer();
  Object.assign(large.content.map.layers[0], { source: 'data:image/png;base64,' + largeImage.toString('base64'), width: 1900, height: 1500 });
  const region = { x: 990, y: 980, width: 128, height: 128 };
  const detail = await observeScene(root, manifest, large, { region, overlay: false });
  const result = await sharp(Buffer.from(detail.images[0].data, 'base64')).removeAlpha().raw().toBuffer();
  const expected = await sharp(largeImage).extract({ left: 1000, top: 1000, width: 128, height: 128 }).raw().toBuffer();
  assert.deepEqual(result, expected, 'A high-entropy map can be inspected across two tile boundaries with original pixels');
  const overview = await observeScene(root, manifest, large, { maxWidth: 512, maxHeight: 512, overlay: false });
  assert.equal(overview.images[0].width, 512, 'The complete large map can be rendered at overview scale');
  await assert.rejects(observeScene(root, manifest, document, { revision: 2 }), /不匹配/);
  const bad = structuredClone(document);
  bad.content.materials[0].project.assets[0].source = 'https://example.invalid/image.png';
  await assert.rejects(observeScene(root, manifest, bad), /先导入外部图片/);
  bad.content.materials[0].project.assets[0].source = 'data:image/png;base64,YmFk';
  await assert.rejects(observeScene(root, manifest, bad), /无法完整加载/);
  bad.content.materials[0].project.assets = [];
  await assert.rejects(observeScene(root, manifest, bad), /缺少/);
  const flipped = { ...instance, flipH: true, scale: 2, anchor: { x: 3, y: 6 } };
  const render = objectRenderState(flipped, material);
  assert.deepEqual(render.origin, { x: 16, y: -2 });
  assert.equal(render.outerTransform, 'translate(16 -2) scale(-2 2)');
  const animated = structuredClone(material);
  animated.project.objects[0].visual.idleAnimation = 'idle';
  animated.project.objects[0].visual.clips = [{ name: 'idle', fps: 2, loop: true, frames: [{ assetId: 'red', duration: 1 }, { assetId: 'second', duration: 2 }] }];
  assert.equal(objectRenderState(instance, animated, { time: 0.6 }).assetId, 'second');
  assert.equal(objectRenderState(instance, animated, { time: 1.6 }).assetId, 'red');
  const floating = createScene('Floating art bounds');
  const floatingProject = structuredClone(project);
  floatingProject.objects[0].visual.float = true;
  const floatingMaterial = addMaterial(floating, floatingProject, floatingProject.objects[0].definitionId);
  const floatingInstance = addInstance(floating, floatingMaterial.id, 0, 0);
  const stableSelection = instanceRect(floatingInstance, floatingMaterial);
  const floatingObservation = await observeScene(root, manifest, { id: floating.id, kind: 'scene', revision: 1, content: floating }, { time: Math.PI / 4, overlay: false });
  assert.deepEqual(instanceRect(floatingInstance, floatingMaterial), stableSelection, 'Floating art must not move the frontend selection rectangle.');
  assert.equal(floatingObservation.viewport.y, stableSelection.y + 5);
  assert.deepEqual(floatingObservation.objects[0].selectionRect, stableSelection);
  assert.equal(floatingObservation.objects[0].rect.y, stableSelection.y + 5);
  const floatingPixels = await sharp(Buffer.from(floatingObservation.images[0].data, 'base64')).raw().toBuffer();
  assert.equal(floatingPixels.filter((_, index) => index % 4 === 3 && floatingPixels[index] === 255).length, 400, 'Automatic observation framing must retain all 20×20 floating art pixels.');
  const linked = structuredClone(document);
  const gate = createObject('toggle');
  Object.assign(gate.visual, object.visual);
  Object.assign(gate.behavior.states[0].appearance, { visible: true, solidEnabled: true });
  Object.assign(gate.behavior.states[1].appearance, { visible: false, solidEnabled: false });
  gate.definitionId = linked.content.materials[0].project.objects[0].definitionId;
  linked.content.materials[0].project.objects = [gate];
  const switchProject = createProject(); switchProject.objects = [createObject('toggle')];
  switchProject.objects[0].behavior.states[0].appearance.tint = '#b48d55';
  const switchMaterial = addMaterial(linked.content, switchProject, switchProject.objects[0].definitionId);
  const switchInstance = addInstance(linked.content, switchMaterial.id, 65, 65);
  linked.content.links = [{ id: 'switch-gate', sourceInstanceId: switchInstance.id, event: 'toggled', targetInstanceId: instance.id, action: 'set_toggle', value: 'source_toggle', enabled: true }];
  const authored = JSON.stringify(linked);
  const replayOptions = { region: { x: -10, y: -20, width: 100, height: 100 }, overlay: false };
  const opened = await observeScene(root, manifest, linked, { ...replayOptions, events: [{ type: 'request', instanceId: switchInstance.id }] });
  const openPixels = await sharp(Buffer.from(opened.images[0].data, 'base64')).raw().toBuffer();
  assert.deepEqual([...openPixels.subarray((20 * 100 + 15) * 4, (20 * 100 + 15) * 4 + 4)], [0, 0, 255, 255], 'Link replay hides the real gate pixels.');
  assert.equal(opened.objects.find(o => o.id === instance.id).visible, false);
  assert.equal(opened.objects.find(o => o.id === instance.id).solidEnabled, false);
  assert.ok(opened.simulation.events.some(e => e.name === 'link_applied'));
  const closedAgain = await observeScene(root, manifest, linked, { ...replayOptions, events: [{ type: 'request', instanceId: switchInstance.id }, { type: 'request', instanceId: switchInstance.id }] });
  const closedPixels = await sharp(Buffer.from(closedAgain.images[0].data, 'base64')).raw().toBuffer();
  assert.deepEqual([...closedPixels.subarray((20 * 100 + 15) * 4, (20 * 100 + 15) * 4 + 4)], [255, 0, 0, 255]);
  assert.equal(closedAgain.objects.find(o => o.id === instance.id).solidEnabled, true);
  assert.deepEqual([...closedPixels.subarray((53 * 100 + 75) * 4, (53 * 100 + 75) * 4 + 4)], [54, 120, 55, 255], 'Placeholder uses the Godot/interactable base color multiplied by the active state tint.');
  assert.equal(JSON.stringify(linked), authored, 'Replay must not write runtime state into the saved scene.');
  linked.content.map.warnings = ['此背景尚未配置地图碰撞。请设置并检查碰撞后再验证游戏行为。', 'Keep source review note'];
  assert.equal(sceneWarnings(linked.content).length, 2);
  linked.content.map.collisions = [[{ x: 0, y: 80 }, { x: 90, y: 80 }, { x: 90, y: 90 }]];
  assert.deepEqual(sceneWarnings(linked.content), ['Keep source review note'], 'Adding explicit geometry resolves only the generated no-collision warning.');
  await assert.rejects(observeScene(root, manifest, linked, { events: [], time: 1 }), /time|tick/);
  console.log('Scene observation: saved-version rendering, ordering, ROI, source confinement, transforms and frame timing passed.');
} finally {
  assert.ok(path.dirname(root) === path.resolve(os.tmpdir()) && path.basename(root).startsWith('forge-observation-'), 'Unsafe test cleanup path');
  await rm(root, { recursive: true, force: true });
}
